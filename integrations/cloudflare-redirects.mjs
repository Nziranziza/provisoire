import { appendFile, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';

/**
 * Writes `dist/_redirects` so Cloudflare Pages answers legacy paths with a real
 * 301 instead of the meta-refresh HTML page Astro emits for a static build.
 *
 * Cloudflare follows `_redirects` before it serves a matching asset, so the
 * generated pages stay as a fallback for other hosts and `astro preview`.
 *
 * Free-plan ceiling is 2,000 static rules; this map produces well under 100.
 *
 * @param {Record<string, string>} redirects source path → destination path
 * @param {number} [status]
 * @returns {import('astro').AstroIntegration}
 */
export default function cloudflareRedirects(redirects, status = 301) {
  return {
    name: 'cloudflare-redirects',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const entries = Object.entries(redirects);
        const lines = [
          '# Generated by integrations/cloudflare-redirects.mjs — do not edit.',
          '# Source of truth: src/lib/redirect-map.mjs',
          ...entries.map(([from, to]) => `${from} ${to} ${status}`),
        ];
        const target = new URL('_redirects', dir);

        // `public/_redirects` is copied into dist before this hook runs; keep
        // any hand-written rules and append the generated ones.
        if (existsSync(target)) {
          const existing = await readFile(target, 'utf8');
          const separator = existing.endsWith('\n') ? '' : '\n';
          await appendFile(target, `${separator}\n${lines.join('\n')}\n`);
        } else {
          await writeFile(target, `${lines.join('\n')}\n`);
        }

        logger.info(`Wrote ${entries.length} rules to _redirects`);
      },
    },
  };
}
